#!/bin/bash

# Script: generate_init.sh
# Description: Creates or updates __init__.py with imports from all Python files in the current directory
# Usage: ./generate_init.sh

set -e  # Exit immediately if a command exits with a non-zero status

# Function to display error messages
error_exit() {
    echo "ERROR: $1" >&2
    exit 1
}

# Get current directory name
CURRENT_DIR=$(basename "$(pwd)")
echo "Current directory: $CURRENT_DIR"

# Check if __init__.py already exists and create backup if needed
if [ -f "__init__.py" ]; then
    echo "Found existing __init__.py, creating backup..."
    cp "__init__.py" "__init__.py.bak" || error_exit "Failed to create backup of __init__.py"
    echo "Backup created as __init__.py.bak"
fi

# Create a temporary file for building the new __init__.py content
TEMP_FILE=$(mktemp) || error_exit "Failed to create temporary file"
trap 'rm -f "$TEMP_FILE"' EXIT

# Find all Python files in the current directory (excluding __init__.py)
echo "Scanning for Python files..."
PY_FILES=()
while IFS= read -r file; do
    # Skip __init__.py and only include direct .py files (no subdirectories)
    if [[ "$(basename "$file")" != "__init__.py" && "$(dirname "$file")" == "." ]]; then
        PY_FILES+=("$file")
    fi
done < <(find . -maxdepth 1 -type f -name "*.py" | sort)

# Check if any Python files were found
if [ ${#PY_FILES[@]} -eq 0 ]; then
    echo "No Python files found in the current directory!"
    echo "Creating an empty __init__.py file..."
    echo "# Automatically generated by generate_init.sh" > "__init__.py"
    echo "__all__ = []" >> "__init__.py"
    exit 0
fi

# Begin building the __init__.py content
echo "# Automatically generated by generate_init.sh" > "$TEMP_FILE"
echo "# Directory: $CURRENT_DIR" >> "$TEMP_FILE"
echo "" >> "$TEMP_FILE"

# Add import statements and build the __all__ array
MODULE_NAMES=()
for file in "${PY_FILES[@]}"; do
    # Extract the module name (filename without .py extension)
    module=$(basename "$file" .py)
    MODULE_NAMES+=("$module")
    
    # Add import statement
    echo "from $CURRENT_DIR.$module import *" >> "$TEMP_FILE"
done

# Add an empty line and the __all__ variable
echo "" >> "$TEMP_FILE"
echo -n "__all__ = [" >> "$TEMP_FILE"

# Add module names to __all__ with proper quoting
for i in "${!MODULE_NAMES[@]}"; do
    if [ $i -gt 0 ]; then
        echo -n ", " >> "$TEMP_FILE"
    fi
    echo -n "'${MODULE_NAMES[$i]}'" >> "$TEMP_FILE"
done

echo "]" >> "$TEMP_FILE"

# Move the temporary file to __init__.py
mv "$TEMP_FILE" "__init__.py" || error_exit "Failed to create __init__.py"

# Success message
echo "Successfully created __init__.py with ${#MODULE_NAMES[@]} modules:"
for module in "${MODULE_NAMES[@]}"; do
    echo "  - $module"
done

echo "Done!"

